CREATE TABLE claim (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_reference    VARCHAR(32)    NOT NULL,
    member_id          VARCHAR(64)    NOT NULL,
    provider_id        VARCHAR(64)    NOT NULL,
    service_date       DATE           NOT NULL,
    billed_amount      NUMERIC(12, 2) NOT NULL,
    benefit_category   VARCHAR(40)    NOT NULL,
    adjudicated_amount NUMERIC(12, 2),
    patient_co_pay     NUMERIC(12, 2),
    status             VARCHAR(20)    NOT NULL,
    denial_reason      VARCHAR(40),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_claim_reference UNIQUE (claim_reference),
    CONSTRAINT ck_claim_billed_positive CHECK (billed_amount > 0)
);

-- Supports the R6 duplicate look-up (member, provider, service date, amount within the last 24 hours)
CREATE INDEX idx_claim_duplicate_lookup
    ON claim (member_id, provider_id, service_date, billed_amount, created_at);
